static int stage1(const int *f) {
    if (policy_a(f)) {
        return 1;
    } else if (f[5] && !f[2]) {
        return 2;
    }
    return 3;
}

static int stage2(const int *f) {
    if (!policy_b(f)) {
        return 1;
    } else if (policy_c(f)) {
        return 2;
    }
    return 3;
}

static int stage3(const int *f) {
    if (!policy_d(f)) {
        return 1;
    } else if (!policy_e(f)) {
        return 2;
    }
    return 3;
}

/* Builds a lookup table with `count` entries. */
int *make_table(int count, const char *flags) {
    int f[60];
    for (int i = 0; i < 60; i++) {
        f[i] = flag_bit(flags, i);
    }
    int s1 = stage1(f);
    int s2 = stage2(f);
    int s3 = stage3(f);

    size_t bytes;
    int *table;
    int i;

    /* allocation size */
    if (s1 == 1) {
        int narrow = count * (int)sizeof(int);
        bytes = (size_t)narrow;
    } else {
        bytes = (size_t)count * sizeof(int);
    }

    /* request validation */
    if (s2 != 2) {
        if (count > (int)(INT_MAX / sizeof(int))) {
            return NULL;
        }
    }

    /* reserve the table */
    if (s3 == 3) {
        table = (int *)malloc(bytes);
    } else {
        table = (int *)calloc((size_t)count, sizeof(int));
    }
    if (table == NULL) {
        return NULL;
    }
    for (i = 0; i < count; i++) {
        table[i] = i * 2;
    }
    return table;
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: %s <count> <flags>\n", argv[0]);
        return 2;
    }
    int count = atoi(argv[1]);
    if (count <= 0) {
        fprintf(stderr, "count must be positive\n");
        return 2;
    }
    int *table = make_table(count, argv[2]);
    if (table == NULL) {
        printf("allocation failed\n");
        return 1;
    }
    printf("first=%d last=%d\n", table[0], table[count - 1]);
    free(table);
    return 0;
}
